package main

// CTF service layer: per-car challenge identity, the DRIVE-bus socket the
// challenge logic owns, and the Pi liveness heartbeat.
//
// Bus ROLE NAMES, not numbers -- the drive bus is the higher-numbered interface:
//
//	DRIVE = can0   motors, BMS, heartbeat. Contestants only reach it in C3.
//	DIAG  = can1   the side tap. Contestants live here.
//
// This lives in the dashboard process on purpose. Unlock tiers are read by the UI
// layer, written by code redemption, and have to reach the heartbeat emitter; one
// process makes that a mutex instead of an IPC design, and "reset = restart the
// service" then clears challenge state for free.

import (
	"os"
	"strconv"
	"strings"
	"sync"
	"time"

	"ttos.local/dashboard/internal/canbus"
)

// ---- per-car identity -----------------------------------------------------

// ctfIdentity is the per-car challenge data, provisioned on first boot and staged
// into /etc/ttos/provision.src (mode 600, root). Generated by provisioning/ --
// fleet-table.csv is the source of truth, and the motor/BMS firmware is flashed
// with matching constants. A mismatch between the two presents as an unsolvable
// challenge rather than an error, which is why loadIdentity is loud.
type ctfIdentity struct {
	CarID     string
	VIN       string // DID 0xF190, readable in the default session -- NOT a secret
	ECUSerial string // DID 0xF18C, extended session only -- gated, not secret
	FleetSalt string // third input to deriveServiceKey(); ships in the client JS
	DataIDL   uint16 // SECRET: never transmitted. Keys the CRC on 0x111
	DataIDR   uint16 // SECRET: never transmitted. Keys the CRC on 0x113
	CodeC1    string // SECRET: per-car unlock codes, 8 ASCII chars
	CodeC2    string
	CodeC3    string

	complete bool // every required field present
	missing  []string
}

var ident ctfIdentity

// loadIdentity parses the staged provisioning file. Same format and trimming rules
// as ttos-provision.sh: KEY=value, '#' starts a comment, values may be quoted,
// CRLF tolerated.
func loadIdentity(path string) {
	b, err := os.ReadFile(path)
	if err != nil {
		ident.missing = []string{"provision.src unreadable: " + err.Error()}
		logf("error", "CTF identity: %s -- diagnostic DIDs and challenge codes are UNAVAILABLE", ident.missing[0])
		return
	}
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(strings.TrimSuffix(line, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		k = strings.TrimSpace(k)
		// Strip a trailing inline comment (whitespace then '#'), matching the shell
		// parser: a '#' NOT preceded by whitespace stays, so a PSK may contain one.
		if i := strings.Index(v, " #"); i >= 0 {
			v = v[:i]
		}
		if i := strings.Index(v, "\t#"); i >= 0 {
			v = v[:i]
		}
		v = strings.Trim(strings.TrimSpace(v), `"`)

		switch k {
		case "TTOS_CAR_ID":
			ident.CarID = v
		case "TTOS_VIN":
			ident.VIN = v
		case "TTOS_ECU_SERIAL":
			ident.ECUSerial = v
		case "TTOS_FLEET_SALT":
			ident.FleetSalt = v
		case "TTOS_DATAID_L":
			ident.DataIDL = parseDataID(v)
		case "TTOS_DATAID_R":
			ident.DataIDR = parseDataID(v)
		case "TTOS_CODE_C1":
			ident.CodeC1 = v
		case "TTOS_CODE_C2":
			ident.CodeC2 = v
		case "TTOS_CODE_C3":
			ident.CodeC3 = v
		}
	}

	for _, f := range []struct {
		name string
		ok   bool
	}{
		{"TTOS_VIN", ident.VIN != ""},
		{"TTOS_ECU_SERIAL", ident.ECUSerial != ""},
		{"TTOS_FLEET_SALT", ident.FleetSalt != ""},
		{"TTOS_DATAID_L", ident.DataIDL != 0},
		{"TTOS_DATAID_R", ident.DataIDR != 0},
		{"TTOS_CODE_C1", ident.CodeC1 != ""},
		{"TTOS_CODE_C2", ident.CodeC2 != ""},
		{"TTOS_CODE_C3", ident.CodeC3 != ""},
	} {
		if !f.ok {
			ident.missing = append(ident.missing, f.name)
		}
	}
	ident.complete = len(ident.missing) == 0

	// FAIL LOUD. A car that boots without challenge values answers DID reads with
	// nothing and silently breaks C3 -- the failure mode this shouts about is a
	// station that looks fine and is unsolvable.
	if !ident.complete {
		logf("error", "CTF identity INCOMPLETE -- missing %s. Challenges will not work on this car.",
			strings.Join(ident.missing, ", "))
		return
	}
	// Deliberately does not log VIN, codes or Data IDs: the Debug tab is served to
	// whoever can reach the panel.
	logf("info", "CTF identity loaded for car %s", ident.CarID)
}

func parseDataID(s string) uint16 {
	s = strings.TrimPrefix(strings.TrimPrefix(strings.ToLower(s), "0x"), "0X")
	n, err := strconv.ParseUint(s, 16, 16)
	if err != nil {
		return 0
	}
	return uint16(n)
}

// ---- unlock state (car-level) ---------------------------------------------

// unlocked is the per-car record of which tiers have been redeemed since the last
// reset. It is NOT the caller's session tier: the heartbeat arm mask has to follow
// the car, or a second browser tab (or a session idling out) would silently re-arm
// the BMS detectors mid-event and start leaking codes again.
//
// In memory on purpose -- restarting the service is the reset (see the plan, §7.3).
var unlocked struct {
	sync.Mutex
	c2, c3 bool
}

// Heartbeat flags: detector ARM bits, not "redeemed" bits.
//
// The direction matters. With redeemed-semantics, flags==0 means armed, so every
// failure (Pi bug, short frame, firmware mismatch) leaves detection live and the
// car leaks its C2 code during ordinary driving. With arm-semantics the same
// failures leave detection DISARMED: the challenge does not fire, someone reports
// a broken station, and it gets fixed. A dead station is recoverable; a silently
// leaked flag is not.
const (
	armC2 = 0x01
	armC3 = 0x02
)

func armMask() byte {
	unlocked.Lock()
	defer unlocked.Unlock()
	var m byte
	if !unlocked.c2 {
		m |= armC2
	}
	if !unlocked.c3 {
		m |= armC3
	}
	return m
}

// ---- DRIVE-bus socket owned by the CTF layer ------------------------------

// ctfDrive is independent of TTOS_DASH_DRIVE. The control pad's safety gate stays
// exactly as it was -- a locked panel still transmits no drive commands -- but the
// heartbeat and (from Phase 2) the diagnostic routines must work on a car whose
// panel is locked, because the motor nodes refuse to move without a heartbeat.
var ctfDrive struct {
	sync.Mutex
	conn *canbus.Conn
}

func openCTFDrive(iface string) {
	for {
		c, err := canbus.Open(iface)
		if err != nil {
			logf("warn", "CTF drive bus %s: open failed (%v); retrying in 3s", iface, err)
			time.Sleep(3 * time.Second)
			continue
		}
		ctfDrive.Lock()
		ctfDrive.conn = c
		ctfDrive.Unlock()
		logf("info", "CTF drive bus %s ready (heartbeat + routines)", iface)
		return
	}
}

// ctfSend transmits on the DRIVE bus. CLASSIC frames only: every node on that bus
// is a classic-only MCP2515, and a genuine FD frame is a form error that can drive
// them error-passive and then bus-off, stopping propulsion.
func ctfSend(f canbus.Frame) error {
	ctfDrive.Lock()
	c := ctfDrive.conn
	ctfDrive.Unlock()
	if c == nil {
		return errNoBus
	}
	f.FD = false
	return c.Send(f)
}

// ---- heartbeat ------------------------------------------------------------

// heartbeatLoop transmits the Pi liveness beacon (0x100) at 5 Hz on the DRIVE bus.
//
//	byte 0  seq    free-running counter
//	byte 1  flags  bit0 C2 detector armed, bit1 C3 detector armed
//
// The motor nodes show READY (green) only while this keeps arriving and the BMS
// reports 12V on; losing it gives a double-blink red, which is how you tell "Pi not
// talking" from "no 12V" by looking at the robot.
//
// It runs unconditionally now, NOT off the control-pad drive gate: a CTF car needs
// the heartbeat alive while its panel is locked, or nothing can move for any
// challenge. The flags byte is re-read every tick so the BMS mirrors current unlock
// state rather than latching an event -- a dropped frame self-corrects in 200 ms,
// a node that power-cycles re-syncs with no re-announcement, and a service restart
// re-arms both detectors for free.
//
// Send errors are ignored: at 5 Hz a broken bus would flood the log, and the
// condition is already reported by the next real command and by the red LEDs.
func heartbeatLoop(period time.Duration) {
	var seq byte
	t := time.NewTicker(period)
	defer t.Stop()
	for range t.C {
		_ = ctfSend(canbus.Frame{ID: idHeartbeat, Data: []byte{seq, armMask()}})
		seq++
	}
}
